import XCTest
import CryptoKit
import PlanariumDomain
@testable import PlanariumPresets
@testable import LegacyPresetTestSupport

final class DetectionStagePresetRegressionTests: XCTestCase {
    func testEveryFactoryAndOwnerEncodingMatchesRandpunkteBaseline() throws {
        let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        var evidence = Data()
        var total = 0
        var configurationEvidence = Data()
        var factoryEvidence = Data()
        var historicalFactoryEvidence = Data()
        for directory in [root.appendingPathComponent("Sources/PlanariumPresets/Resources"),
                          root.appendingPathComponent("Tests/PlanariumPresetsTests/Fixtures/Owner")] {
            let files = try FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)
                .filter { $0.pathExtension == "json" }.sorted { $0.lastPathComponent < $1.lastPathComponent }
            // The frozen hashes cover the files that existed at the freeze;
            // later factory presets are pinned by their own tests.
            for file in files where file.lastPathComponent != "\(FactoryPresetDocument.controllerFirstNotesName).sickpreset.json" {
                let data = try Data(contentsOf: file)
                let object = try XCTUnwrap(JSONSerialization.jsonObject(with: data) as? [String: Any])
                let version = try XCTUnwrap(object["formatVersion"] as? Int)
                func compareConfigurations(_ node: Any) throws {
                    if let object = node as? [String: Any] {
                        if object["groupingEnabled"] != nil || object["temporalSmoothing"] != nil {
                            let bytes = try JSONSerialization.data(withJSONObject: object)
                            let encoder = JSONEncoder(); encoder.outputFormatting = [.sortedKeys]
                            let new = try encoder.encode(JSONDecoder().decode(DetectionConfiguration.self, from: bytes))
                            configurationEvidence.append(Data(file.lastPathComponent.utf8)); configurationEvidence.append(new)
                        }
                        for key in object.keys.sorted() { try compareConfigurations(object[key]!) }
                    } else if let array = node as? [Any] { for value in array { try compareConfigurations(value) } }
                }
                try compareConfigurations(object)
                let encoded: Data
                switch version {
                case 1...3: encoded = try PresetCodec.encode(PresetCodec.decode(data))
                case 4: encoded = try PresetDocumentCodec.encode(JSONDecoder().decode(InstrumentPresetV4.self, from: data))
                case 5: encoded = try PresetV5Codec.encode(PresetV5Codec.decode(data))
                case 6: encoded = try PresetV6Codec.encode(PresetV6Codec.decode(data))
                default: XCTFail("Unexpected preset version"); continue
                }
                var historicalEncoding = encoded
                if directory.lastPathComponent == "Resources" {
                    // The old byte oracles retain scene dwell 0.2. Check the
                    // new zero default explicitly, then reconstruct only that
                    // retired field for comparison; keep the frozen hashes.
                    func legacySceneDefaults(_ node: Any) -> Any {
                        if var object = node as? [String: Any] {
                            if object["dwellSeconds"] != nil {
                                XCTAssertEqual(object["dwellSeconds"] as? Double, 0, file.lastPathComponent)
                                object["dwellSeconds"] = 0.2
                            }
                            return object.mapValues(legacySceneDefaults)
                        }
                        if let array = node as? [Any] { return array.map(legacySceneDefaults) }
                        return node
                    }
                    let legacyBytes = try JSONSerialization.data(withJSONObject:
                        legacySceneDefaults(JSONSerialization.jsonObject(with: encoded)))
                    var historical = try PresetV6Codec.decode(legacyBytes)
                    let factoryBaseline = try PresetV6Codec.encode(historical)
                    // Owner-approved factory editor raster, regenerated by
                    // make-harmony-presets.py. Keep the frozen 25-cm oracle
                    // as a separate proof that no other wire content changed.
                    historical.document.editorGrid = .quarterMeter
                    historicalEncoding = try PresetV6Codec.encode(historical)
                    factoryEvidence.append(Data(file.lastPathComponent.utf8)); factoryEvidence.append(factoryBaseline)
                    historicalFactoryEvidence.append(Data(file.lastPathComponent.utf8)); historicalFactoryEvidence.append(historicalEncoding)
                }
                evidence.append(Data(file.lastPathComponent.utf8)); evidence.append(historicalEncoding)
                total += 1
            }
        }
        let hash = SHA256.hash(data: evidence).map { String(format: "%02x", $0) }.joined()
        print("RANDPUNKTE preset digest \(hash), files \(total)")
        XCTAssertEqual(total, 60)
        // Frozen on an isolated cc3802d tree. Legacy v3 sets have historic
        // randomized array order; deterministic hashing permits comparing
        // their complete emitted bytes without altering the product encoder.
        XCTAssertEqual(SHA256.hash(data: configurationEvidence).map { String(format: "%02x", $0) }.joined(),
            "80c5f7e9b6156d83a471a2f581f4a9dcbe0dd1fbeff29780f1064f005e94f2b8")
        XCTAssertEqual(SHA256.hash(data: historicalFactoryEvidence).map { String(format: "%02x", $0) }.joined(),
            "82840e2d743407a618a9a742e7e3569842b085e112f65274f9d3ce29d5aa0f63")
        XCTAssertEqual(SHA256.hash(data: factoryEvidence).map { String(format: "%02x", $0) }.joined(),
            "277b1f644d1bbda9a5aacff5078ae43d588985907cf699e8d6c10d2beca91784")
        if ProcessInfo.processInfo.environment["SWIFT_DETERMINISTIC_HASHING"] == "1" {
            XCTAssertEqual(hash, "5659a89a1a0e04796bf39d8b07b63fa552f731b00c290e9a4343793963c1cea1")
        }
    }
}
